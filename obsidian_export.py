def sanitize_filename(title):
    """
    Sanitize a string to be used as a filename.
    
    Removes or replaces characters that are invalid in filenames.
    
    Args:
        title (str): Original title/name
        
    Returns:
        str: Sanitized filename (without extension)
    """
    
    # Remove or replace invalid characters
    sanitized = re.sub(r'[<>:"/\\|?*]', '', title)
    
    # Replace spaces with underscores
    sanitized = sanitized.replace(' ', '_')
    
    # Limit length
    max_length = 200
    if len(sanitized) > max_length:
        sanitized = sanitized[:max_length]
    
    # Remove leading/trailing periods and spaces
    sanitized = sanitized.strip('. ')
    
    return sanitized


def create_yaml_frontmatter(metadata):
    """
    Generate YAML frontmatter for a markdown file.
    
    Args:
        metadata (dict): Dictionary of metadata fields
        
    Returns:
        str: Formatted YAML frontmatter block
    """
    
    lines = ["---"]
    
    for key, value in metadata.items():
        if isinstance(value, list):
            lines.append(f"{key}:")
            for item in value:
                lines.append(f"  - {item}")
        else:
            lines.append(f"{key}: {value}")
    
    lines.append("---")
    
    return "\n".join(lines)


