def _create_index_file(data, output_dir):
    """
    Create an index markdown file listing all entries.
    
    This serves as a starting point for the Obsidian vault.
    
    Args:
        data (pd.DataFrame): Source data
        output_dir (str): Output directory
    """
    
    index_path = os.path.join(output_dir, 'Index.md')
    
    with open(index_path, 'w', encoding='utf-8') as f:
        # Write YAML frontmatter
        f.write("---\n")
        f.write("title: Philosophical Text Analysis Index\n")
        f.write(f"created: {datetime.now().strftime('%Y-%m-%d')}\n")
        f.write("tags:\n")
        f.write("  - index\n")
        f.write("  - philosophy\n")
        f.write("---\n\n")
        
        # Write index content
        f.write("# Philosophical Text Analysis Index\n\n")
        f.write(f"**Total Entries:** {len(data)}\n\n")
        
        if 'section' in data.columns:
            sections = data['section'].unique()
            f.write(f"**Sections:** {len(sections)}\n\n")
            
            for section in sections:
                section_data = data[data['section'] == section]
                f.write(f"## {section}\n\n")
                f.write(f"- Contains {len(section_data)} entries\n\n")
        
        f.write("\n---\n")
        f.write(f"\n*Generated by philAnalyze on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}*\n")
    
    logger.info(f"Created index file: {index_path}")


