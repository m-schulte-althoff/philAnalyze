def export_metadata_csv(data, output_dir):
    """
    Export metadata as CSV for reference.
    
    Creates a CSV file with all metadata fields for easy reference
    and potential re-import.
    
    Args:
        data (pd.DataFrame): Source data
        output_dir (str): Output directory
    """
    
    metadata_path = os.path.join(output_dir, 'metadata.csv')
    
    # Select only metadata columns (exclude long text)
    metadata_columns = [col for col in data.columns if col != 'text']
    metadata_df = data[metadata_columns]
    
    metadata_df.to_csv(metadata_path, index=False, encoding='utf-8')
    logger.info(f"Exported metadata to {metadata_path}")
